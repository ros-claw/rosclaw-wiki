def code_generate(entity_name: str, wiki_root: str | None = None, language: str = "python") -> dict[str, Any]:
    """MCP tool: generate a code framework for an entity/algorithm.

    Returns:
        Dict with code, citations, warnings, and unresolved_conflicts.
    """
    if wiki_root is None:
        return {"status": "error", "message": "wiki_root is required"}

    result = generate_code_framework(entity_name, wiki_root, language)

    # Log to wiki log
    if result["status"] in ("generated", "blocked"):
        engine.append_log(
            wiki_root,
            f"code_generator | {result['status']} | [[{entity_name}]]"
        )

    return result
